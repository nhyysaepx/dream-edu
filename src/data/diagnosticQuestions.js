/**
 * Dynamically generate a Diagnostic Quiz for any vocabulary set
 * when curated questions aren't pre-defined.
 */
export function getDiagnosticQuestionsForSet(vocabSet) {
  if (vocabSet.id === 'pre-ielts-reading-1') {
    return PRE_IELTS_READING_1_DIAGNOSTIC;
  }

  const terms = vocabSet.terms || [];
  if (terms.length === 0) return [];

  const questions = [];

  // Generate 50% Receptive and 50% Productive questions
  terms.forEach((item, index) => {
    const isReceptive = index % 2 === 0;
    const otherTerms = terms.filter(t => t.id !== item.id);
    const shuffledOthers = [...otherTerms].sort(() => 0.5 - Math.random());
    const distractors = shuffledOthers.slice(0, 3);

    if (isReceptive) {
      // Receptive definition question
      const options = [
        item.definition,
        ...distractors.map(d => d.definition)
      ].sort(() => 0.5 - Math.random());

      questions.push({
        id: `auto-diag-rec-${item.id}`,
        type: 'Receptive',
        targetWord: item.term,
        question: `[Receptive] What is the accurate Vietnamese definition or meaning of "${item.term}"?`,
        correctAnswer: item.definition,
        options,
        rationale: `"${item.term}" translates directly to "${item.definition}". The other choices correspond to different vocabulary terms in this lesson.`
      });
    } else {
      // Productive word in sentence question
      const options = [
        item.term,
        ...distractors.map(d => d.term)
      ].sort(() => 0.5 - Math.random());

      questions.push({
        id: `auto-diag-prod-${item.id}`,
        type: 'Productive',
        targetWord: item.term,
        question: `[Productive] Complete the context with the appropriate term: "Students must understand the concept of ________ (${item.definition}) to master this topic."`,
        correctAnswer: item.term,
        options,
        rationale: `"${item.term}" is the correct English term for "${item.definition}". The other options have different lexical meanings.`
      });
    }
  });

  return questions;
}
